import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as sass from "sass";
import postcss from "postcss";

const root = fileURLToPath(new URL("../", import.meta.url));
const tabler = sass.compile(path.join(root, "css/tabler-components.scss"), {
  loadPaths: [path.join(root, "node_modules")], style: "compressed",
  silenceDeprecations: ["import", "global-builtin", "color-functions", "if-function"],
  logger: sass.Logger.silent
});
await writeFile(path.join(root, "css/tabler-components.css"),
  "/*! Tabler UI 1.4.0 / Bootstrap: MIT. Selected components, generated by npm run build:ui. */\n@layer tabler{" + tabler.css + "}\n");

// Retain presentation for the existing engine's generated markup, not its old shell.
const source = postcss.parse(await readFile(path.join(root, "css/style.css"), "utf8"));
const allowed = /(?:stop-|integration-|rail-|brt-|gps-dot|route-(?:popup|source|alert|meta|header|heading|title|summary|primary|identity|system|name|direction|condition|geometry|compare|plan|status|stats|operational)|legend-|webgis-(?:concept|exploration)|global-search-(?:result|group|empty|loading)|info-(?:modal|status|release|changelog)|product-tour|tour-|basemap-|opacity-grid|leaflet-(?:popup|tooltip)|poi-popup)/;
const shell = /(?:filter-panel|right-info-panel|right-info-body|global-search-panel|route-detail-card|route-detail-body|route-detail-toggle|lower-right-nav|bottom-toolbar|floating-|desktopUtilityRail)/;
function retain(node) {
  if (node.type === "rule") {
    const selectors = node.selectors.filter(selector =>
      selector === ":root" || (allowed.test(selector) && !shell.test(selector)));
    if (!selectors.length) return null;
    const copy = node.clone({ selector: selectors.join(","), nodes: [] });
    for (const child of node.nodes) {
      if (child.type !== "decl") continue;
      if (node.selector === ":root" && !child.prop.startsWith("--")) continue;
      copy.append(child.clone({ important: false }));
    }
    return copy.nodes.length ? copy : null;
  }
  if (node.type === "atrule" && node.nodes) {
    if (node.name.endsWith("keyframes")) return node.clone();
    if (!["media", "supports"].includes(node.name)) return null;
    const copy = node.clone({ nodes: [] });
    for (const child of node.nodes) { const item = retain(child); if (item) copy.append(item); }
    return copy.nodes.length ? copy : null;
  }
  return null;
}
const legacy = postcss.root();
for (const node of source.nodes) { const item = retain(node); if (item) legacy.append(item); }
legacy.walkComments(node => node.remove());
legacy.walkDecls(node => { node.important = false; node.raws.between = ":"; });
legacy.walk(node => {
  node.raws.before = ""; node.raws.after = "";
  if (node.type === "rule" || node.type === "atrule") node.raws.between = "";
});
await writeFile(path.join(root, "css/legacy-components.css"),
  "/* Generated from css/style.css for existing dynamic markup. Shell rules excluded; priority flags removed. */\n@layer legacy-components{" + legacy.toString() + "}\n");
console.log(JSON.stringify({ tablerBytes: Buffer.byteLength(tabler.css), legacyRules: legacy.nodes.length,
  legacyBytes: Buffer.byteLength(legacy.toString()) }));
